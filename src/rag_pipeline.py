"""RAG Pipeline module connecting Retriever with LLM providers (Gemini API, Ollama, Mock).
Handles prompt engineering, bilingual grounding, and source citation extraction.
"""

from typing import List, Dict, Any, Optional
import os
import requests
from src.retriever import PDFRetriever, RetrievedChunk
from config import (
    GEMINI_API_KEY,
    DEFAULT_GEMINI_MODEL,
    DEFAULT_OLLAMA_BASE_URL,
    DEFAULT_OLLAMA_MODEL,
)

SYSTEM_PROMPT_TEMPLATE = """You are an expert AI PDF Assistant specialized in accurate, grounded Document Question-Answering.

CRITICAL INSTRUCTIONS:
1. Answer the question using ONLY the provided Document Context below.
2. If the answer cannot be found or deduced directly from the context, clearly state:
   - In English: "I could not find information about this in the provided document(s)."
   - In Arabic: "لم أجد معلومات حول هذا الموضوع في المستند(ات) المقدمة."
   Do NOT attempt to make up or hallucinate answers.
3. ALWAYS cite your sources and page numbers whenever stating a fact, using the format: [Source: <filename>, Page: <page_number>].
4. Language instruction:
   - If the user asks in Arabic, answer in professional Arabic.
   - If the user asks in English, answer in clear English.
   - If bilingual, match the dominant language of the prompt.
5. Provide well-structured answers using bullet points, bold key terms, and concise paragraphs.

DOCUMENT CONTEXT:
{context}

USER QUESTION:
{question}

GROUNDED ANSWER:"""


class RAGPipeline:
    """End-to-end Retrieval Augmented Generation pipeline."""

    def __init__(
        self,
        retriever: PDFRetriever,
        provider: str = "gemini",
        gemini_api_key: Optional[str] = None,
        gemini_model: str = DEFAULT_GEMINI_MODEL,
        ollama_base_url: str = DEFAULT_OLLAMA_BASE_URL,
        ollama_model: str = DEFAULT_OLLAMA_MODEL,
    ):
        self.retriever = retriever
        self.provider = provider
        self.gemini_api_key = gemini_api_key or GEMINI_API_KEY
        self.gemini_model = gemini_model
        self.ollama_base_url = ollama_base_url
        self.ollama_model = ollama_model

    def _call_gemini(self, prompt: str) -> str:
        """Invokes Google Gemini via official google-genai SDK."""
        key = self.gemini_api_key or os.getenv("GEMINI_API_KEY")
        if not key:
            raise ValueError(
                "Gemini API Key is missing. Please provide a GEMINI_API_KEY in .env or the UI."
            )

        from google import genai

        client = genai.Client(api_key=key)
        interaction = client.interactions.create(
            model=self.gemini_model,
            input=prompt,
        )
        return interaction.output_text or "No response generated by model."

    def _call_ollama(self, prompt: str) -> str:
        """Invokes local Ollama instance."""
        url = f"{self.ollama_base_url.rstrip('/')}/api/generate"
        payload = {
            "model": self.ollama_model,
            "prompt": prompt,
            "stream": False,
        }
        try:
            response = requests.post(url, json=payload, timeout=60)
            response.raise_for_status()
            data = response.json()
            return data.get("response", "No response from Ollama.")
        except Exception as e:
            raise RuntimeError(
                f"Failed to connect to Ollama at {self.ollama_base_url}. Ensure Ollama is running: {e}"
            ) from e

    def _call_mock(self, prompt: str, retrieved_chunks: List[RetrievedChunk], question: str) -> str:
        """Fallback mock generator when offline / without active API key."""
        if not retrieved_chunks:
            return (
                "لم أجد معلومات حول هذا الموضوع في المستند(ات) المقدمة.\n\n"
                "(I could not find information about this in the provided document.)\n\n"
                "*Tip: Provide your Gemini API Key in the sidebar for full conversational generation.*"
            )

        citations = [f"[{c.source}, Page {c.page}]" for c in retrieved_chunks[:2]]
        citation_str = ", ".join(citations)

        return (
            f"**[Demo / Grounded Answer Mode]**\n\n"
            f"Based directly on the retrieved document context {citation_str}:\n\n"
            f"> \"{retrieved_chunks[0].content[:250]}...\"\n\n"
            f"**Sources Referenced:** {citation_str}\n\n"
            f"*Note: Running in offline demo mode. Enter a Gemini API Key in the sidebar for generative answers!*"
        )

    def generate_answer(
        self,
        question: str,
        top_k: Optional[int] = None,
        similarity_threshold: Optional[float] = None,
        source_filter: Optional[str] = None,
    ) -> Dict[str, Any]:
        """
        Runs the full RAG pipeline: retrieval -> prompt synthesis -> LLM generation.
        """
        # 1. Retrieve relevant chunks
        retrieved_chunks = self.retriever.retrieve(
            query=question,
            top_k=top_k,
            similarity_threshold=similarity_threshold,
            source_filter=source_filter,
        )

        # 2. Format context
        context_str = self.retriever.format_context_for_prompt(retrieved_chunks)

        # 3. Construct prompt
        formatted_prompt = SYSTEM_PROMPT_TEMPLATE.format(
            context=context_str,
            question=question,
        )

        # 4. Generate answer
        answer_text = ""
        error_msg = None

        if self.provider == "gemini":
            try:
                answer_text = self._call_gemini(formatted_prompt)
            except Exception as e:
                # If Gemini fails (e.g. invalid key or network), fall back gracefully to mock
                error_msg = str(e)
                answer_text = (
                    f"⚠️ **Gemini API Error**: {error_msg}\n\n"
                    f"Falling back to extractive context preview:\n\n"
                    + self._call_mock(formatted_prompt, retrieved_chunks, question)
                )
        elif self.provider == "ollama":
            try:
                answer_text = self._call_ollama(formatted_prompt)
            except Exception as e:
                error_msg = str(e)
                answer_text = (
                    f"⚠️ **Ollama Error**: {error_msg}\n\n"
                    + self._call_mock(formatted_prompt, retrieved_chunks, question)
                )
        else:
            answer_text = self._call_mock(formatted_prompt, retrieved_chunks, question)

        # 5. Extract unique citations
        unique_citations = []
        seen = set()
        for chunk in retrieved_chunks:
            cite_key = (chunk.source, chunk.page)
            if cite_key not in seen:
                seen.add(cite_key)
                unique_citations.append(
                    {
                        "source": chunk.source,
                        "page": chunk.page,
                        "similarity": chunk.similarity,
                        "snippet": chunk.content[:200] + "...",
                    }
                )

        return {
            "question": question,
            "answer": answer_text,
            "citations": unique_citations,
            "retrieved_chunks": [c.__dict__ for c in retrieved_chunks],
            "context_used": context_str,
            "error": error_msg,
        }

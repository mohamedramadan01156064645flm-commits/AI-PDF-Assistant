"""End-to-end integration test script for AI PDF Assistant.
Validates PDF loading, chunking, embeddings, vector storage, retrieval, and RAG pipeline.
"""

import sys
from pathlib import Path

# Force UTF-8 stdout on Windows console
if sys.platform == "win32":
    try:
        sys.stdout.reconfigure(encoding="utf-8")
        sys.stderr.reconfigure(encoding="utf-8")
    except Exception:
        pass

# Add project root to path
sys.path.insert(0, str(Path(__file__).resolve().parent))

from create_sample_pdf import generate_sample_pdf
from src.document_loader import PDFDocumentLoader
from src.text_splitter import DocumentSplitter
from src.embeddings import EmbeddingManager
from src.vector_store import ChromaVectorStore
from src.retriever import PDFRetriever
from src.rag_pipeline import RAGPipeline
from src.chatbot import PDFChatbot
from config import PDFS_DIR


def run_all_tests():
    print("=" * 60)
    print("🧪 Running End-to-End Tests for AI PDF Assistant")
    print("=" * 60)

    # 1. Generate sample PDF
    print("\n[Step 1] Generating sample bilingual PDF...")
    sample_pdf = generate_sample_pdf()
    assert sample_pdf.exists(), "Sample PDF was not generated"
    print(f"✅ Sample PDF verified at: {sample_pdf}")

    # 2. Test Document Loader
    print("\n[Step 2] Testing PDFDocumentLoader with PyMuPDF...")
    loader = PDFDocumentLoader()
    pages = loader.load_pdf(sample_pdf)
    assert len(pages) == 3, f"Expected 3 pages, got {len(pages)}"
    assert pages[0].metadata["page"] == 1, "Page 1 metadata incorrect"
    assert "Supervised Learning" in pages[0].page_content, "Supervised Learning text not found in page 1"
    print(f"✅ PDFDocumentLoader successfully extracted {len(pages)} pages with metadata.")

    # 3. Test Text Splitter
    print("\n[Step 3] Testing DocumentSplitter...")
    splitter = DocumentSplitter(chunk_size=400, chunk_overlap=80)
    chunks = splitter.split_pages(pages)
    assert len(chunks) > 0, "No chunks generated by splitter"
    stats = splitter.get_split_stats(chunks)
    print(f"✅ DocumentSplitter created {stats['total_chunks']} chunks. Stats: {stats}")
    assert all("page" in c.metadata for c in chunks), "Metadata lost in chunking"

    # 4. Test Embeddings
    print("\n[Step 4] Testing HuggingFace SentenceTransformer Embeddings...")
    embed_mgr = EmbeddingManager()
    sample_texts = ["Machine learning is AI", "Deep learning uses neural networks"]
    vectors = embed_mgr.embed_documents(sample_texts)
    assert len(vectors) == 2, "Embedding count mismatch"
    assert len(vectors[0]) == embed_mgr.embedding_dimension, "Vector dimension mismatch"
    similarity = embed_mgr.cosine_similarity(vectors[0], vectors[1])
    print(f"✅ Embeddings generated successfully. Dimension: {embed_mgr.embedding_dimension}, Sim: {similarity:.4f}")

    # 5. Test Vector Store (ChromaDB)
    print("\n[Step 5] Testing ChromaVectorStore persistence & indexing...")
    vstore = ChromaVectorStore()
    vstore.reset()
    added_count = vstore.add_chunks(chunks)
    assert added_count == len(chunks), "Chunk count mismatch in vector store"
    assert vstore.count() == len(chunks), "Chroma count mismatch"
    sources = vstore.get_indexed_sources()
    assert "machine_learning_basics.pdf" in sources, "Source not listed in indexed sources"
    print(f"✅ ChromaVectorStore indexed {vstore.count()} chunks. Sources: {sources}")

    # 6. Test Semantic Retrieval
    print("\n[Step 6] Testing Semantic Retrieval with PDFRetriever...")
    retriever = PDFRetriever(vstore, default_top_k=3, default_threshold=0.2)
    query_en = "What is the difference between supervised and unsupervised learning?"
    retrieved_en = retriever.retrieve(query_en)
    assert len(retrieved_en) > 0, "Retrieval returned no chunks for English query"
    top_chunk = retrieved_en[0]
    print(f"✅ Retrieval successful: top chunk from Page {top_chunk.page} (sim: {top_chunk.similarity:.4f})")
    assert top_chunk.page == 1, f"Expected Page 1 for supervised learning, got Page {top_chunk.page}"

    # Arabic query test (bilingual concept retrieval)
    query_ar = "Supervised vs unsupervised learning (التعلم الخاضع للإشراف وغير الخاضع للإشراف)"
    retrieved_ar = retriever.retrieve(query_ar, similarity_threshold=0.2)
    assert len(retrieved_ar) > 0, "Retrieval returned no chunks for Arabic query"
    print(f"✅ Arabic/bilingual retrieval successful: retrieved {len(retrieved_ar)} chunks (top sim: {retrieved_ar[0].similarity:.4f}).")

    # 7. Test RAG Pipeline (Mock provider for offline testing)
    print("\n[Step 7] Testing RAG Pipeline generation...")
    rag = RAGPipeline(retriever=retriever, provider="mock")
    answer = rag.generate_answer(query_en)
    assert "citations" in answer, "Citations missing from RAG response"
    assert len(answer["citations"]) > 0, "Expected at least 1 citation"
    print(f"✅ RAG pipeline returned grounded answer with citations: {answer['citations'][0]}")

    # 8. Test Chatbot with Follow-up Question
    print("\n[Step 8] Testing Conversational Multi-turn Chatbot...")
    bot = PDFChatbot(rag)
    turn1 = bot.ask("What is machine learning?")
    assert len(bot.history) == 1, "Chat history not updated"
    turn2 = bot.ask("What are its main types?")
    assert len(bot.history) == 2, "Follow-up turn not added"
    print(f"✅ Chatbot history maintained. Follow-up processed.")

    print("\n" + "=" * 60)
    print("🎉 ALL TESTS PASSED SUCCESSFULLY! The RAG system is fully functional.")
    print("=" * 60)


if __name__ == "__main__":
    run_all_tests()
